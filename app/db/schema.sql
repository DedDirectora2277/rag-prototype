-- Схема прототипа. Плейсхолдер {embed_dim} подставляет app.db.client.init_db().
-- Все операторы идемпотентны: init_db() можно вызывать при каждом старте.

CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE IF NOT EXISTS documents (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source       text        NOT NULL UNIQUE,
    doc_type     text        NOT NULL,
    title        text,
    content_hash text        NOT NULL,
    metadata     jsonb       NOT NULL DEFAULT '{}'::jsonb,
    created_at   timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS chunks (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id    bigint    NOT NULL REFERENCES documents (id) ON DELETE CASCADE,
    parent_id      bigint    REFERENCES chunks (id) ON DELETE CASCADE,
    chunk_index    integer   NOT NULL,
    chunk_type     text      NOT NULL,
    content        text      NOT NULL,
    -- russian / english для текста, simple для кода (идентификаторы не стеммятся)
    ts_config      regconfig NOT NULL DEFAULT 'simple',
    tsv            tsvector  GENERATED ALWAYS AS (to_tsvector(ts_config, content)) STORED,
    embedding      vector({embed_dim}),
    is_retrievable boolean   NOT NULL DEFAULT true,
    metadata       jsonb     NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT retrievable_has_embedding CHECK (NOT is_retrievable OR embedding IS NOT NULL)
);

-- Parent-чанки (is_retrievable = false) не ищутся напрямую, поэтому индекс частичный.
CREATE INDEX IF NOT EXISTS chunks_embedding_hnsw
    ON chunks USING hnsw (embedding vector_cosine_ops)
    WHERE is_retrievable;

CREATE INDEX IF NOT EXISTS chunks_tsv_gin ON chunks USING gin (tsv);
CREATE INDEX IF NOT EXISTS chunks_document_id ON chunks (document_id);
CREATE INDEX IF NOT EXISTS chunks_parent_id ON chunks (parent_id);
CREATE INDEX IF NOT EXISTS documents_doc_type ON documents (doc_type);
